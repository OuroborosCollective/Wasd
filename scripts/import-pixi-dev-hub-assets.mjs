#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const repoRoot = process.cwd();
const archivePath = path.join(repoRoot, 'public/archive/wasd-pixi-asset-packs.json');
const sourceMetadataPath = path.join(repoRoot, 'docs/archive/pixi-first-batch-source-metadata.json');
const runtimeManifestPath = path.join(
  repoRoot,
  'apps/client-2d/public/2d-assets/manifests/pixi-dev-hub-first-batch.json',
);
const creditsDir = path.join(repoRoot, 'apps/client-2d/public/2d-assets/credits');

function slugify(value) {
  return String(value)
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function assertVisualOnlyPolicy(manifest) {
  const rules = manifest.coreRules || [];
  const required = [
    'WorldTick and AREKernel remain authoritative.',
    'No sprite placement may create authoritative gameplay state.',
  ];

  for (const rule of required) {
    if (!rules.includes(rule)) {
      throw new Error(`Missing required asset safety rule: ${rule}`);
    }
  }
}

function indexById(items) {
  return new Map((items || []).map((item) => [item.id, item]));
}

function requireSourceGate(pack, metadata) {
  const failures = [];

  if (!metadata) failures.push('missing source metadata entry');
  if (metadata && metadata.sourceVerified !== true) failures.push('sourceVerified must be true');
  if (metadata && !metadata.sourceUrl) failures.push('sourceUrl is required');
  if (metadata && !metadata.licenseUrl) failures.push('licenseUrl is required');
  if (metadata && metadata.binaryImportStatus === 'blocked-until-source-verified') {
    failures.push('binaryImportStatus is blocked-until-source-verified');
  }

  if (failures.length > 0) {
    return {
      ok: false,
      id: pack.id,
      failures,
    };
  }

  return {
    ok: true,
    id: pack.id,
    merged: {
      ...pack,
      ...metadata,
    },
  };
}

async function readJson(filePath) {
  return JSON.parse(await readFile(filePath, 'utf8'));
}

async function writeJson(filePath, value) {
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, `${JSON.stringify(value, null, 2)}\n`);
}

async function writeCredits(pack) {
  const creditPath = path.join(creditsDir, `${slugify(pack.id)}.json`);
  const credit = {
    schemaVersion: '1.0.0',
    packId: pack.id,
    license: pack.license,
    licenseName: pack.licenseName || pack.license,
    sourceStatus: pack.sourceVerified ? 'source-verified' : 'required-before-binary-import',
    sourceUrl: pack.sourceUrl || null,
    licenseUrl: pack.licenseUrl || null,
    attributionRequired: Boolean(pack.attributionRequired),
    binaryImportStatus: pack.binaryImportStatus || 'planned',
    notes: [
      'This file is generated by scripts/import-pixi-dev-hub-assets.mjs.',
      'Asset content is visual-only and must not define authoritative gameplay state.',
      'Downloaded binaries must come from sourceUrl only.',
    ],
  };
  await writeJson(creditPath, credit);
  return path.relative(repoRoot, creditPath);
}

async function ensureTargetDirectory(target) {
  const safeTarget = target.replace(/^\//, '');
  const absolute = path.join(repoRoot, safeTarget);
  await mkdir(absolute, { recursive: true });
  const gitkeep = path.join(absolute, '.gitkeep');
  await writeFile(gitkeep, '');
  return path.relative(repoRoot, absolute);
}

async function main() {
  const archive = await readJson(archivePath);
  assertVisualOnlyPolicy(archive);

  const sourceMetadata = await readJson(sourceMetadataPath);
  const sourceById = indexById(sourceMetadata.packs);

  const runtimeManifest = await readJson(runtimeManifestPath);
  const plannedPacks = archive.firstIntegrationBatch || [];

  const gateResults = plannedPacks.map((pack) => requireSourceGate(pack, sourceById.get(pack.id)));
  const blocked = gateResults.filter((result) => !result.ok);
  if (blocked.length > 0) {
    const details = blocked
      .map((result) => `- ${result.id}: ${result.failures.join('; ')}`)
      .join('\n');
    throw new Error(`Pixi asset source gate failed:\n${details}`);
  }

  const results = [];
  for (const result of gateResults) {
    const pack = result.merged;
    const target = pack.target || pack.targetPath;
    if (!target) {
      throw new Error(`Pack ${pack.id} has no target path.`);
    }

    const targetDirectory = await ensureTargetDirectory(target);
    const creditFile = await writeCredits(pack);

    results.push({
      id: pack.id,
      decision: pack.decision,
      priority: pack.priority,
      license: pack.license,
      licenseName: pack.licenseName,
      sourceUrl: pack.sourceUrl,
      licenseUrl: pack.licenseUrl,
      sourceVerified: pack.sourceVerified,
      binaryImportStatus: pack.binaryImportStatus,
      status: 'planned-source-gated',
      targetDirectory,
      creditFile,
      nextRequiredActions: [
        'Implement official-source download step.',
        'Download asset pack from sourceUrl only.',
        'Normalize filenames to kebab-case.',
        'Generate Pixi-compatible atlas or manifest metadata.',
        'Run pnpm --filter @wasd/client-2d validate:assets.',
      ],
    });
  }

  runtimeManifest.generatedBy = 'scripts/import-pixi-dev-hub-assets.mjs';
  runtimeManifest.lastPlannedAt = new Date().toISOString();
  runtimeManifest.sourceGate = {
    metadataPath: path.relative(repoRoot, sourceMetadataPath),
    status: 'passed',
    checkedPacks: results.length,
  };
  runtimeManifest.plannedResults = results;
  await writeJson(runtimeManifestPath, runtimeManifest);

  const planPath = path.join(repoRoot, 'apps/client-2d/public/2d-assets/manifests/pixi-dev-hub-import-plan.json');
  await writeJson(planPath, {
    schemaVersion: '1.0.0',
    generatedAt: new Date().toISOString(),
    sourceManifest: path.relative(repoRoot, archivePath),
    sourceMetadata: path.relative(repoRoot, sourceMetadataPath),
    runtimeManifest: path.relative(repoRoot, runtimeManifestPath),
    authorityPolicy: 'visual-only: WorldTick and AREKernel remain authoritative',
    sourceGate: {
      status: 'passed',
      checkedPacks: results.length,
    },
    results,
  });

  console.log(`Pixi Dev Hub source gate passed for ${results.length} packs.`);
  console.log(`Plan: ${path.relative(repoRoot, planPath)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
