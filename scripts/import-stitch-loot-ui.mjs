#!/usr/bin/env node
import { copyFile, mkdir, readdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import path from 'node:path';

const root = process.cwd();
const inbox = path.join(root, '.asset-inbox', 'stitch');
const work = path.join(root, '.asset-work', 'stitch');
const out = path.join(root, 'client', 'public', 'assets', 'stitch-loot-ui');
const registryFile = path.join(root, 'client', 'src', 'loot', 'ui', 'LootVisualRegistry.generated.ts');
const assetExt = new Set(['.png', '.jpg', '.jpeg', '.webp', '.svg', '.json', '.html', '.css']);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(full));
    else files.push(full);
  }
  return files.sort((a, b) => a.localeCompare(b));
}

function slug(value) {
  return value.toLowerCase().replace(/[^a-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '') || 'asset';
}

async function sha256(file) {
  return createHash('sha256').update(await readFile(file)).digest('hex');
}

async function unzipArchives() {
  await rm(work, { recursive: true, force: true });
  await mkdir(work, { recursive: true });
  const archives = (await walk(inbox)).filter((file) => path.extname(file).toLowerCase() === '.zip');
  for (const archive of archives) {
    const name = slug(path.basename(archive, '.zip'));
    const target = path.join(work, name);
    await mkdir(target, { recursive: true });
    const result = spawnSync('unzip', ['-q', archive, '-d', target], { stdio: 'inherit' });
    if (result.status !== 0) throw new Error(`Could not unzip ${archive}`);
  }
  return archives;
}

function classify(rel) {
  const lower = rel.toLowerCase();
  const rarity = ['mythic', 'legendary', 'epic', 'rare', 'magic', 'common'].find((x) => lower.includes(x));
  const group = lower.includes('affix') ? 'affix'
    : lower.includes('rarity') ? 'rarity'
    : lower.includes('monster') ? 'monster'
    : lower.includes('npc') ? 'npc'
    : lower.includes('faction') ? 'faction'
    : lower.includes('item') ? 'item'
    : 'stitch';
  return { group, rarity: rarity ?? null };
}

await unzipArchives();
await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
await mkdir(path.dirname(registryFile), { recursive: true });

const staged = (await walk(work)).filter((file) => assetExt.has(path.extname(file).toLowerCase()));
const manifest = [];

for (const file of staged) {
  const rel = path.relative(work, file).replaceAll(path.sep, '/');
  const targetRel = rel.split('/').map(slug).join('/');
  const target = path.join(out, targetRel);
  await mkdir(path.dirname(target), { recursive: true });
  await copyFile(file, target);

  const ext = path.extname(target).toLowerCase();
  let croppedRel = null;
  if (['.png', '.jpg', '.jpeg', '.webp'].includes(ext)) {
    croppedRel = targetRel.replace(new RegExp(`${ext}$`), `.cropped${ext}`);
    await copyFile(target, path.join(out, croppedRel));
  }

  const meta = classify(rel);
  manifest.push({
    id: slug(targetRel.replace(/\.[^.]+$/, '')),
    source: rel,
    path: `/assets/stitch-loot-ui/${targetRel}`,
    croppedPath: croppedRel ? `/assets/stitch-loot-ui/${croppedRel}` : null,
    sha256: await sha256(target),
    group: meta.group,
    rarity: meta.rarity,
  });
}

manifest.sort((a, b) => a.id.localeCompare(b.id));
await writeFile(path.join(out, 'manifest.json'), `${JSON.stringify({ schemaVersion: '1.0.0', generatedFrom: '.asset-inbox/stitch', count: manifest.length, assets: manifest }, null, 2)}\n`);
await writeFile(path.join(out, 'crop-manifest.json'), `${JSON.stringify({ schemaVersion: '1.0.0', mode: 'deterministic-copy-crop-fallback', count: manifest.filter((x) => x.croppedPath).length, assets: manifest.filter((x) => x.croppedPath) }, null, 2)}\n`);

const ts = `/* Auto-generated by scripts/import-stitch-loot-ui.mjs. Do not edit by hand. */\nexport type LootVisualGroup = 'affix' | 'rarity' | 'monster' | 'npc' | 'faction' | 'item' | 'stitch';\n\nexport interface LootVisualRegistryEntry {\n  id: string;\n  source: string;\n  path: string;\n  croppedPath: string | null;\n  sha256: string;\n  group: LootVisualGroup;\n  rarity: string | null;\n}\n\nexport const LOOT_VISUAL_REGISTRY = ${JSON.stringify(manifest, null, 2)} as const satisfies readonly LootVisualRegistryEntry[];\n\nexport function findLootVisual(id: string): LootVisualRegistryEntry | undefined {\n  return LOOT_VISUAL_REGISTRY.find((entry) => entry.id === id);\n}\n\nexport function findLootVisualByRarity(rarity: string): LootVisualRegistryEntry | undefined {\n  const normalized = rarity.toLowerCase();\n  return LOOT_VISUAL_REGISTRY.find((entry) => entry.group === 'rarity' && entry.rarity === normalized)\n    ?? LOOT_VISUAL_REGISTRY.find((entry) => entry.rarity === normalized);\n}\n`;

await writeFile(registryFile, ts);
console.log(`Imported ${manifest.length} Stitch loot UI assets into ${path.relative(root, out)}`);
